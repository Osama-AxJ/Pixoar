namespace Pixoar.Core.Models;

/// <summary>
/// Identifies image formats supported by Pixoar.
/// </summary>
public enum ImageFormat
{
    /// <summary>
    /// Portable Network Graphics.
    /// </summary>
    Png,

    /// <summary>
    /// JPEG image format.
    /// </summary>
    Jpeg,

    /// <summary>
    /// WebP image format.
    /// </summary>
    Webp,

    /// <summary>
    /// Bitmap image format.
    /// </summary>
    Bmp,

    /// <summary>
    /// Tagged Image File Format.
    /// </summary>
    Tiff,

    /// <summary>
    /// DirectDraw Surface texture format.
    /// </summary>
    Dds
}
